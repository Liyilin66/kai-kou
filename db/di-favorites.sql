-- Shared favorites for RA, DI, RTS and the profile page.
-- Keep this historical filename so existing setup links continue to work.
begin;

create table if not exists public.favorites (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  task_type text not null default 'DI',
  question_id text not null,
  created_at timestamptz not null default now()
);

create unique index if not exists favorites_user_task_question_uidx
  on public.favorites (user_id, task_type, question_id);

alter table public.favorites enable row level security;

-- New tables are not automatically exposed on every Supabase project.
-- Ownership policies below still apply to every authenticated request.
revoke all on public.favorites from anon, authenticated;
grant select, insert, delete on public.favorites to authenticated;
grant usage, select on sequence public.favorites_id_seq to authenticated;
grant all on public.favorites to service_role;
grant usage, select on sequence public.favorites_id_seq to service_role;

drop policy if exists "favorites_select_own" on public.favorites;
drop policy if exists "favorites_insert_own" on public.favorites;
drop policy if exists "favorites_delete_own" on public.favorites;

create policy "favorites_select_own"
on public.favorites
for select
to authenticated
using (auth.uid() = user_id);

create policy "favorites_insert_own"
on public.favorites
for insert
to authenticated
with check (auth.uid() = user_id);

create policy "favorites_delete_own"
on public.favorites
for delete
to authenticated
using (auth.uid() = user_id);

commit;
